"""Night art for Calm Combo (Neo Geo CD).

A scene picture can have a hand-painted night copy next to it:
`lake/sky.png` -> `lake/sky_night.png`.  The night copy has the same pixels
in different colours, so it costs no sprite memory: this tool turns each one
into a colour table (day colour -> night colour) in src/night_maps.h, and the
game fades from the day colours into the night colours at dusk.

    python3 tools/make_night.py             write src/night_maps.h
    python3 tools/make_night.py --samples   also create starter night copies
                                            for pictures that have none
                                            (never overwrites a night file)

Rules (tools/check_assets.py checks them): same size as the day file, the
same pixels transparent, and each day colour turns into exactly one night
colour.  Pictures without a night copy keep the automatic night tint.
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
GFX = os.path.join(HERE, '..', 'src', 'assets', 'gfx')
OUT = os.path.join(HERE, '..', 'src', 'night_maps.h')
MAG = (255, 0, 255)

# pictures that are tinted by time of day: file -> (C symbol, sample style)
# (the sun, moon, fireflies and glitter are lights: they never get a night copy)
PICTS = [
    ('lake/sky.png',        'cc_lake_sky',   'sky'),
    ('lake/ridge_mid.png',  'cc_ridge_mid',  'far'),
    ('lake/ridge_near.png', 'cc_ridge_near', 'near'),
    ('lake/water.png',      'cc_water',      'water'),
    ('beach/sky_sea.png',   'cc_sky_sea',    'sky'),
    ('beach/shore.png',     'cc_shore',      'near'),
    ('beach/wave.png',      'cc_wave',       'near'),
    ('beach/palm.png',      'cc_palm',       'silhouette'),
    ('beach/umbrella.png',  'cc_umbrella',   'silhouette'),
    ('window/city.png',     'cc_city',       'city'),
    ('window/rain.png',     'cc_rain',       'rain'),
    ('window/droplet.png',  'cc_droplet',    'rain'),
    ('window/frame.png',    'cc_frame',      'lamp'),
    ('window/steam.png',    'cc_steam',      'lamp'),
]

def snap(v):
    return max(0, min(248, int(round(v / 8.0)) * 8))

def night_colour(rgb, style):
    """Starter night colour: moonlit blue outdoors, warm lamplight indoors."""
    r, g, b = rgb
    lum = 0.30 * r + 0.59 * g + 0.11 * b
    if style == 'city' and rgb == (88, 96, 112):          # lit windows
        return (248, 208, 136)
    if style == 'rain':                                   # rain catches the city light
        return tuple(snap(v) for v in (lum * 0.40 + r * 0.10, lum * 0.46 + g * 0.10, lum * 0.60 + b * 0.15))
    if style == 'lamp':                                   # inside, by the lamp
        out = (lum * 0.50 + r * 0.22, lum * 0.36 + g * 0.16, lum * 0.20 + b * 0.10)
    else:
        k = {'sky': 0.85, 'far': 0.80, 'near': 0.75, 'water': 0.90,
             'silhouette': 0.45, 'city': 0.70}[style]
        out = ((lum * 0.26 + r * 0.10) * k + 6,
               (lum * 0.34 + g * 0.10) * k + 8,
               (lum * 0.58 + b * 0.16) * k + 22)
    return tuple(snap(v) for v in out)

def is_clear(px):
    return px[3] == 0 or px[:3] == MAG

def make_sample(rel, style):
    day = Image.open(os.path.join(GFX, rel)).convert('RGBA')
    out = day.copy()
    a, b = day.load(), out.load()
    cache = {}
    for y in range(day.size[1]):
        for x in range(day.size[0]):
            p = a[x, y]
            if is_clear(p):
                continue
            c = cache.get(p[:3])
            if c is None:
                c = cache[p[:3]] = night_colour(p[:3], style)
            b[x, y] = c + (255,)
    path = os.path.join(GFX, rel[:-4] + '_night.png')
    out.save(path)
    print('wrote sample', rel[:-4] + '_night.png')

def key(rgb):
    """5-bit-per-channel colour packed into 15 bits, the way the game reads it."""
    return ((rgb[0] >> 3) << 10) | ((rgb[1] >> 3) << 5) | (rgb[2] >> 3)

def colour_map(rel):
    day = Image.open(os.path.join(GFX, rel)).convert('RGBA')
    night = Image.open(os.path.join(GFX, rel[:-4] + '_night.png')).convert('RGBA')
    if day.size != night.size:
        sys.exit('%s: the night copy is a different size (run tools/check_assets.py)' % rel)
    a, b = day.load(), night.load()
    m = {}
    for y in range(day.size[1]):
        for x in range(day.size[0]):
            d, n = a[x, y], b[x, y]
            if is_clear(d) or is_clear(n):
                continue
            m.setdefault(key(d[:3]), key(n[:3]))
    return sorted(m.items())

def main():
    if '--samples' in sys.argv:
        for rel, sym, style in PICTS:
            if not os.path.exists(os.path.join(GFX, rel[:-4] + '_night.png')):
                make_sample(rel, style)
    lines = ['/* Generated by tools/make_night.py from the *_night.png files: do not edit.',
             ' * Each table is pairs of (day colour, night colour), 5 bits per channel',
             ' * packed as r << 10 | g << 5 | b, sorted by day colour. */', '']
    entries = []
    for rel, sym, style in PICTS:
        if not os.path.exists(os.path.join(GFX, rel[:-4] + '_night.png')):
            continue
        m = colour_map(rel)
        words = []
        for d, n in m:
            words += ['0x%04x' % d, '0x%04x' % n]
        lines.append('static const WORD NM_%s[] = {' % sym)
        for k in range(0, len(words), 8):
            lines.append('    ' + ', '.join(words[k:k + 8]) + ',')
        lines.append('};')
        entries.append('    { &%s, NM_%s, %d },' % (sym, sym, len(m)))
        print('%-22s %3d colours' % (rel[:-4] + '_night.png', len(m)))
    lines.append('')
    lines.append('#define N_NIGHT_MAPS %d' % len(entries))
    lines.append('static const NightMap NIGHT_MAPS[] = {')
    lines += entries or ['    { 0, 0, 0 }']
    lines.append('};')
    text = '\n'.join(lines) + '\n'
    old = open(OUT).read() if os.path.exists(OUT) else None
    if text != old:
        open(OUT, 'w').write(text)
        print('wrote src/night_maps.h (%d night copies)' % len(entries))
    else:
        print('src/night_maps.h is up to date (%d night copies)' % len(entries))

if __name__ == '__main__':
    main()
